    /**
     * Приблизительное определение пола автора по имени и фамилии.
     * Может ошибаться на редких именах и иностранных фамилиях.
     */
    fun isFemaleAuthor(name: String): Boolean {
        val parts = name.split(Regex("\\s+")).filter { it.isNotBlank() }
        if (parts.isEmpty()) return false
        val norm = parts.map(::normalize)
        // Ищем женскую фамилию в любом слове (кроме инициалов длиной 1 символ).
        if (norm.any { it.length > 1 && FEMALE_SURNAME_SUFFIXES.any { suffix -> it.endsWith(suffix) } }) return true
        // Проверяем полные имена (покрывает и формат «Фамилия И.», и «Имя Фамилия»).
        return norm.any { it.length > 1 && it in FEMALE_FIRST_NAMES }
    }

    fun filterFemale(books: List<Book>, enabled: Boolean): List<Book> =
        if (enabled) books.filterNot { book ->
            book.author != null && isFemaleAuthor(book.author!!)
        } else {
            books
        }

    private fun normalize(s: String): String {
        val lower = s.lowercase().replace('ё', 'е')
        val sb = StringBuilder()
        for (ch in lower) {
            when {
                ch.code in 0x0430..0x044F -> sb.append(ch)
                ch in 'a'..'z' -> sb.append(LATIN_TO_CYRILLIC[ch] ?: ch.toString())
                else -> Unit
            }
        }
        return sb.toString()
    }
